/**
 * Exports the data tables of @actors/human (races, features, muscle terms, expressions, shape
 * sliders, body types, test clips) as JSON for the Rust port, so both read the same numbers:
 *
 *   npx tsx rust/golden/export-data.ts
 *
 * writes rust/crates/actors-human/data/human.json and rust/crates/actors-generator/data/generator.json
 * (catalog tables of @actors/generator). CI runs it and fails if the file changed, so
 * edit the TypeScript tables and re-run this instead of editing the JSON.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import {
  BLINK, BODY_TYPES, BONE_GROUPS, EXPRESSIONS, FEATURE_TARGETS, MAX_HEAD_SCALE, MUSCLE_TERMS, RACES, RACE_IDS, RACE_STYLES, RIDE, CLIPS,
  SHAPE_SLIDERS, WRINKLE_GROUPS, WRINKLES, YOUTH, ADULT_MIN_AGE, MAX_AGE, DEFAULT_PARAMS, DEFAULT_RACE, EAR_MASKS,
  BEARD_STYLES, HORN_STYLES, TAIL_STYLES, ROBOT_HEADS, ROBOT_EARS, ROBOT_PLATING, DEFAULT_ROBOT, DEFAULT_SKELETAL,
} from "../../packages/human/src/index";
import {
  OUTFITS, HAIR_COLORS, GARMENT_COLORS, ROBOT_FINISHES, ROBOT_PALETTES, SKELETAL_PALETTES, ROBOT_HEAD_LABELS, PROCEDURAL_HAIR, PROCEDURAL_HAIR_RACE,
  PAINTED_BROWS, THEMES, THEME_FLAGS, GARMENT_THEMES, HAIR_THEMES, RACE_THEMES, KIND_THEMES, ALLOW_PRESETS,
} from "../../packages/generator/src/index";
import { HAIR_STYLE_MESHES, BROW_STYLE_MESHES } from "../../packages/generator/src/racelook";
import { IRIS_PRESETS } from "../../packages/three/src/materials";
import { PUPILS, SKIN_PATTERNS } from "../../packages/three/src/racepatterns";

const data = {
  note: "Generated by rust/golden/export-data.ts from @actors/human. Do not edit.",
  adultMinAge: ADULT_MIN_AGE,
  maxAge: MAX_AGE,
  defaultParams: DEFAULT_PARAMS,
  defaultRace: DEFAULT_RACE,
  raceIds: RACE_IDS,
  races: RACES,
  raceStyles: RACE_STYLES,
  youth: YOUTH,
  maxHeadScale: MAX_HEAD_SCALE,
  boneGroups: Object.fromEntries(Object.entries(BONE_GROUPS).map(([k, re]) => [k, re.source])),
  featureTargets: FEATURE_TARGETS,
  earMasks: EAR_MASKS,
  muscleTerms: MUSCLE_TERMS,
  expressions: EXPRESSIONS,
  blink: BLINK,
  wrinkleGroups: WRINKLE_GROUPS,
  wrinkles: WRINKLES,
  shapeSliders: SHAPE_SLIDERS,
  bodyTypes: BODY_TYPES,
  axisClips: [...CLIPS, RIDE],
};

const out = new URL("../crates/actors-human/data/human.json", import.meta.url);
writeFileSync(out, JSON.stringify(data, null, 1) + "\n");
console.log(`wrote ${out.pathname}`);

const generator = {
  note: "Generated by rust/golden/export-data.ts from @actors/generator. Do not edit.",
  beardStyles: BEARD_STYLES,
  hornStyles: HORN_STYLES,
  tailStyles: TAIL_STYLES,
  pupils: Object.keys(PUPILS),
  skinPatterns: Object.keys(SKIN_PATTERNS),
  irisPresets: Object.keys(IRIS_PRESETS),
  robotHeads: ROBOT_HEADS,
  robotHeadLabels: ROBOT_HEAD_LABELS,
  robotEars: ROBOT_EARS,
  robotPlating: ROBOT_PLATING,
  defaultRobot: DEFAULT_ROBOT,
  defaultSkeletal: DEFAULT_SKELETAL,
  robotFinishes: ROBOT_FINISHES,
  robotPalettes: ROBOT_PALETTES,
  skeletalPalettes: SKELETAL_PALETTES,
  outfits: OUTFITS,
  hairColors: HAIR_COLORS,
  garmentColors: GARMENT_COLORS,
  proceduralHair: PROCEDURAL_HAIR,
  proceduralHairRace: PROCEDURAL_HAIR_RACE,
  paintedBrows: PAINTED_BROWS,
  hairStyleMeshes: HAIR_STYLE_MESHES,
  browStyleMeshes: BROW_STYLE_MESHES,
  themes: THEMES,
  themeFlags: THEME_FLAGS,
  garmentThemes: GARMENT_THEMES,
  hairThemes: HAIR_THEMES,
  raceThemes: RACE_THEMES,
  kindThemes: KIND_THEMES,
  allowPresets: ALLOW_PRESETS,
};

mkdirSync(new URL("../crates/actors-generator/data/", import.meta.url), { recursive: true });
const out2 = new URL("../crates/actors-generator/data/generator.json", import.meta.url);
writeFileSync(out2, JSON.stringify(generator, null, 1) + "\n");
console.log(`wrote ${out2.pathname}`);
